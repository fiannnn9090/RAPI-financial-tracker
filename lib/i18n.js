/* Versi non-hook untuk libs murni: lang eksplisit, tidak menyentuh ACTIVE_LANG.
   Param `fallback` opsional: dipakai bila kunci tak ada di DICT (mis. badge dari DB). */
export function tl(lang, key, vars, fallback) {
  const entry = DICT[key];
  const text = entry ? entry[lang] : null;
  return interpolate(text ?? fallback ?? key, vars);
}

export function t(key, vars) {
  return tl(ACTIVE_LANG, key, vars);
}

import { createContext, useContext } from 'react';

export const LangContext = createContext('id');

export function useT() {
  const lang = useContext(LangContext);
  return (key, vars) => {
    const entry = DICT[key];
    return interpolate(entry ? entry[lang] : key, vars);
  };
}
